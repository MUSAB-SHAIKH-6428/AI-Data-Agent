from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add 

# Base Model : to define and validate the structure of data.

class AgentSchema(BaseModel):
    messages : Annotated[list, add] = Field(..., description = "list of messages to be provided by the agent")
    user_question : str = Field(..., description = "The Original Question asked by the User")
    curated_ques : str = Field(..., description = "Curated User Question")
    prompt_query_context : str = Field(..., description = "a detailed prommpt with with SQL DB context that will help agent to generate SQL query")
    generated_sql_query : str = Field(..., description="The SQL query generated by the agent based on the curated question and prompt context")
    is_safe : Literal["Yes", "No"] = Field(..., description = "indicated whether the SQL query is safe to execute or not")
    comments : str = Field(..., description="Comments regarding the safety of the generated SQL query")
    
    sql_query_execution_result : str = Field(..., description="The result of executing the generated SQL query on the database")

    final_answer : str = Field(..., description = "the final answer generated by the agent based on the SQL query execution result and curated question")

class JudgeSchema(BaseModel):
    answer : Literal["Yes", "No"] = Field(..., description =  "indicated whether the SQL query is safe to execute or not")
    comments : str = Field(..., description = "Additional comments or feedback from the judge regarding the SQL query")